const regexes = [
  /(^|\.)127\.\d+\.\d+\.\d+(?:\.|$)/,
  /(^|\.)192\.168\.\d+\.\d+(?:\.|$)/,
  /(^|\.)10\.\d+\.\d+\.\d+(?:\.|$)/,
  /(^|\.)172\.(1[6-9]|2[0-9]|3[0-1])\.\d+\.\d+(?:\.|$)/,
  /(^|\.)169\.254\.\d+\.\d+(?:\.|$)/
];

const testCases = [
  'localhost',
  '127.0.0.1',
  '127.0.0.1.nip.io',
  'project127.com',
  '192.168.1.1',
  '192.168.1.1.xip.io',
  '10.0.0.1',
  '10.0.0.1.nip.io',
  '172.16.0.1',
  '169.254.169.254',
  'my169.254.com'
];

testCases.forEach(tc => {
  const matches = regexes.some(r => r.test(tc));
  console.log(`${tc}: ${matches}`);
});
